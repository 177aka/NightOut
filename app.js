const themeColors = { soft: '#3b82f6', fun: '#8b5cf6', flirt: '#14b8a6', hardcore: '#ef4444' };
const themeNames = { soft: 'Chill', fun: 'Fun', flirt: 'Flirt', hardcore: 'Hardcore' };

let state = { players: [], genders: {}, scores: {}, history: {}, level: 'soft', haptic: true, noOrientationLimit: false };

if (localStorage.getItem('nightOut_state')) {
    try { state = JSON.parse(localStorage.getItem('nightOut_state')); } catch(e){}
}

const saveState = () => localStorage.setItem('nightOut_state', JSON.stringify(state));
const vibrate = (pattern) => { if (state.haptic && navigator.vibrate) navigator.vibrate(pattern); };

const renderPlayers = () => {
    const list = document.getElementById('player-list');
    list.innerHTML = '';
    state.players.forEach((p) => {
        const div = document.createElement('div');
        div.className = `tag ${state.genders[p]}`;
        const genderText = state.genders[p] === 'M' ? 'Garçon' : 'Fille';
        div.innerHTML = `${p} <span class="gender-label">${genderText}</span> <span class="remove" onclick="removePlayer('${p}')">✕</span>`;
        list.appendChild(div);
    });
    document.getElementById('player-count').innerText = state.players.length;
    saveState();
};

const addPlayer = () => {
    const input = document.getElementById('new-player');
    const genderSelect = document.getElementById('new-player-gender');
    const name = input.value.trim();
    
    if (name && !state.players.includes(name)) {
        if (!state.genders) state.genders = {};
        if (!state.scores) state.scores = {};
        if (!state.history) state.history = {};

        state.players.push(name);
        state.genders[name] = genderSelect ? genderSelect.value : 'M';
        state.scores[name] = 0;
        state.history[name] = [];
        
        input.value = '';
        renderPlayers();
    }
};

window.removePlayer = (name) => {
    state.players = state.players.filter(p => p !== name);
    delete state.genders[name];
    delete state.scores[name];
    delete state.history[name];
    renderPlayers();
};

document.getElementById('add-player-btn').addEventListener('click', addPlayer);
document.getElementById('new-player').addEventListener('keypress', (e) => { if(e.key === 'Enter') addPlayer(); });

const startGame = () => {
    if (state.players.length < 2) return alert("Il faut au moins 2 joueurs !");
    state.level = document.getElementById('level-select').value;
    state.haptic = document.getElementById('setting-haptic').checked;
    state.noOrientationLimit = document.getElementById('setting-orientation').checked;
    
    document.documentElement.style.setProperty('--current-theme', themeColors[state.level]);
    document.getElementById('current-theme-indicator').innerText = themeNames[state.level];
    
    document.getElementById('home-screen').classList.remove('active');
    document.getElementById('game-screen').classList.add('active');
    
    buildOrbit();
};

document.getElementById('start-game-btn').addEventListener('click', startGame);
document.getElementById('back-btn').addEventListener('click', () => {
    document.getElementById('game-screen').classList.remove('active');
    document.getElementById('home-screen').classList.add('active');
});

const buildOrbit = () => {
    const container = document.getElementById('orbit-container');
    container.innerHTML = '';
    const radius = 110;

    state.players.forEach((p, i) => {
        const bubble = document.createElement('div');
        bubble.className = 'bubble';
        bubble.id = `bubble-${p}`;
        if (state.genders[p] === 'M') bubble.style.borderColor = 'rgba(56, 189, 248, 0.5)';
        if (state.genders[p] === 'F') bubble.style.borderColor = 'rgba(244, 63, 94, 0.5)';
        
        const angle = (i / state.players.length) * (2 * Math.PI) - (Math.PI / 2);
        bubble.style.setProperty('--tx', `${Math.cos(angle) * radius}px`);
        bubble.style.setProperty('--ty', `${Math.sin(angle) * radius}px`);
        bubble.style.setProperty('--invRot', `0deg`);
        
        bubble.innerHTML = `<div class="name">${p}</div><div class="points" id="pts-${p}">${state.scores[p]} pts</div>`;
        container.appendChild(bubble);
    });
};

const updatePointsUI = () => {
    state.players.forEach(p => {
        const el = document.getElementById(`pts-${p}`);
        if(el) el.innerText = `${state.scores[p]} pts`;
    });
};

let currentPlayer = '', targetPlayer = '';
let currentRotation = 0;

const playTurn = () => {
    document.getElementById('play-btn').classList.add('disabled');
    document.querySelectorAll('.bubble').forEach(b => {
        b.classList.remove('active-player', 'target-player', 'fake-player', 'shake');
        const playerName = b.id.replace('bubble-', '');
        if (state.genders[playerName] === 'M') b.style.borderColor = 'rgba(56, 189, 248, 0.5)';
        if (state.genders[playerName] === 'F') b.style.borderColor = 'rgba(244, 63, 94, 0.5)';
    });

    const container = document.getElementById('orbit-container');
    currentRotation += (3 * 360) + Math.floor(Math.random() * 360);
    
    container.style.transform = `rotate(${currentRotation}deg)`;
    document.querySelectorAll('.bubble').forEach(b => {
        b.style.setProperty('--invRot', `${-currentRotation}deg`);
    });

    let hapInterval = setInterval(() => vibrate(30), 150);

    setTimeout(() => {
        clearInterval(hapInterval);

        if (Math.random() < 0.15) {
            vibrate([400, 200, 400]);
            return showGlobalEvent();
        }

        let shuffled = [...state.players].sort(() => 0.5 - Math.random());
        currentPlayer = shuffled[0];
        
        let potentialTargets = state.players.filter(p => p !== currentPlayer);
        
        if (!state.noOrientationLimit && (state.level === 'flirt' || state.level === 'hardcore')) {
            const oppositeGender = state.genders[currentPlayer] === 'M' ? 'F' : 'M';
            let oppTargets = potentialTargets.filter(p => state.genders[p] === oppositeGender);
            if (oppTargets.length > 0) {
                potentialTargets = oppTargets;
            }
        }
        
        potentialTargets = potentialTargets.sort(() => 0.5 - Math.random());
        targetPlayer = potentialTargets[0];

        if (state.players.length > 2 && Math.random() < 0.3) {
            let remainingForFake = state.players.filter(p => p !== currentPlayer && p !== targetPlayer);
            let fakePlayer = remainingForFake.length > 0 ? remainingForFake.sort(() => 0.5 - Math.random())[0] : targetPlayer;
            
            document.getElementById(`bubble-${currentPlayer}`).classList.add('active-player');
            document.getElementById(`bubble-${fakePlayer}`).classList.add('fake-player');
            vibrate([100, 50, 100]);

            setTimeout(() => {
                document.getElementById('game-board').classList.add('shake');
                vibrate([300, 100, 300]); 
                
                document.getElementById(`bubble-${fakePlayer}`).classList.remove('fake-player');
                document.getElementById(`bubble-${targetPlayer}`).classList.add('target-player');
                
                setTimeout(openChoiceModal, 800);
            }, 1200);
        } else {
            document.getElementById(`bubble-${currentPlayer}`).classList.add('active-player');
            document.getElementById(`bubble-${targetPlayer}`).classList.add('target-player');
            vibrate([100, 50, 100]);
            setTimeout(openChoiceModal, 800);
        }

    }, 3500); 
};

document.getElementById('play-btn').addEventListener('click', playTurn);

