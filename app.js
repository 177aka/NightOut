const openChoiceModal = () => {
    stepChallenge.classList.add('hidden');
    stepAlert.classList.add('hidden');
    stepChoice.classList.remove('hidden');
    
    document.getElementById('active-player-name').innerText = currentPlayer;
    
    if(!state.history[currentPlayer]) state.history[currentPlayer] = [];
    const hist = state.history[currentPlayer];
    document.getElementById('btn-action').classList.remove('disabled');
    document.getElementById('btn-truth').classList.remove('disabled');

    if (hist.length >= 2) {
        if (hist[hist.length-1] === 'action' && hist[hist.length-2] === 'action') document.getElementById('btn-action').classList.add('disabled');
        if (hist[hist.length-1] === 'truth' && hist[hist.length-2] === 'truth') document.getElementById('btn-truth').classList.add('disabled');
    }

    modalOverlay.classList.remove('hidden');
};

const selectType = (type) => {
    if(!state.history[currentPlayer]) state.history[currentPlayer] = [];
    state.history[currentPlayer].push(type);
    if(state.history[currentPlayer].length > 3) state.history[currentPlayer].shift();
    
    const pool = database[state.level][type + 's'];
    let text = pool[Math.floor(Math.random() * pool.length)];
    
    text = text.replace(/%p1%/g, currentPlayer).replace(/%p2%/g, targetPlayer);
    
    const targetGender = state.genders[targetPlayer];
    if (targetGender === 'F') {
        text = text.replace(/obligé\b/g, 'obligée');
        text = text.replace(/isolé\b/g, 'isolée');
        text = text.replace(/bandé\b/g, 'bandée');
    } else {
        text = text.replace(/obligée\b/g, 'obligé');
        text = text.replace(/isolée\b/g, 'isolé');
    }

    stepChoice.classList.add('hidden');
    stepChallenge.classList.remove('hidden');
    
    const badge = document.getElementById('challenge-type-badge');
    badge.innerText = type === 'action' ? 'ACTION' : 'VÉRITÉ';
    badge.style.color = type === 'action' ? '#ef4444' : '#3b82f6';
    
    document.getElementById('challenge-text').innerHTML = text;
};

